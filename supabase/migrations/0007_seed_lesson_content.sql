## แก่นของเกมนี้
เราไม่บังคับน้องด้วยมือ (ไม่จับ ไม่ดัน ไม่ดุ) — เราแค่ **จัดสถานการณ์ให้ "การเลือกถูก" เป็นทางที่พาไปสู่สิ่งที่น้องอยากได้** แล้วน้อง **ค้นพบเอง**

> พูดง่าย ๆ: เราไม่บอกน้องว่าต้องทำอะไร เราจัดสถานการณ์ให้น้องค้นพบเองว่าอะไรเวิร์ก

## น้องจะได้อะไร
- ควบคุมตัวเองได้ แม้มีของที่อยากได้อยู่ตรงหน้า
- ไม่คว้า/ไม่แย่งของโดยพลการ (ปลอดภัยมาก โดยเฉพาะเวลาของอันตรายตกพื้น)
- เรียนรู้ "การเลือกให้ถูก" ที่เป็นฐานของทุกเกมต่อไป
- รู้จักคำสำคัญ 3 คำ: **cook · search · get it**

## เตรียมของ
- ขนมชิ้นเล็กที่น้องชอบ
- พื้นที่สงบ เริ่มในบ้านก่อน
- ใจเย็น ๆ และมือที่นิ่ง

## วิธีเล่น

### ส่วนที่ 1 — ขนมจากมือ
1. วางขนมบนฝ่ามือ แบมือให้น้องเห็น
2. ถ้าน้องพุ่งเข้ามาจะแย่ง → **กำมือ** (แค่กำ ปิดขนมไว้)
3. **สำคัญที่สุด: กำมือเฉย ๆ อย่ายกมือหนี** — เพราะทันทีที่เรายกมือหนี เกมจะเปลี่ยนจาก "ฝึกให้น้องเลือก" กลายเป็น "เกมไล่ล่า" ทันที น้องบางตัวยิ่งตื่นเต้น ยิ่งอยากคว้า เราต้องการให้น้องเรียนรู้ที่จะนิ่ง ไม่ใช่ไล่จับมือ
4. รอจนน้อง **เลือกเอง** ที่จะถอย/นิ่ง (ไม่พยายามแย่ง) → แบมือให้กิน
5. ทำซ้ำจนน้องเข้าใจว่า "นิ่ง = ได้กิน / แย่ง = ไม่ได้"
6. พอน้องเริ่มนิ่งเป็น ค่อยใส่คำ:
   - **"cook"** = พูด*ก่อน*ยื่นขนม (บอกล่วงหน้าว่าขนมกำลังมา)
   - **"get it"** = พอน้องยับยั้งใจได้ ไม่แย่ง จึงพูด "get it" — คำอนุญาตว่า "กินได้เลย เก่งมาก"

### ส่วนที่ 2 — ขนมจากพื้น
1. วางขนมลงพื้นทีละชิ้น
2. ถ้าน้องเข้ามาจะกิน → ทำมือเป็น **"กระโจม"** ครอบขนมไว้ (ให้น้องยังเห็นขนม แต่กินไม่ได้)
3. **ทำไมต้องเป็นกระโจม ไม่ใช่ฝ่ามือปิดมิด?** เพราะเป้าหมายคือ "เห็นแต่ไม่แย่ง" ไม่ใช่ "ไม่เห็นเลยก็เลยไม่แย่ง" — ถ้าปิดจนน้องมองไม่เห็น น้องบางตัวจะเลิกสนใจ แต่นั่นไม่ใช่การเลือก เราต้องการให้น้องเห็นสิ่งที่อยากได้เต็ม ๆ แล้วยัง **เลือก** ที่จะไม่คว้าเอง
4. พอน้องนิ่ง → พูด **"get it"** ให้กิน

### สอนคำว่า "search"
- พูดคำว่า **"search"** ก่อน แล้วค่อยโยนขนมลงพื้น — อย่าพูดพร้อมกับโยน
- **ทำไม?** เพราะเราต้องการให้ "คำ" มาก่อน "ขนม" เสมอ น้องจะเรียนรู้ว่า *ได้ยินคำนี้ = เดี๋ยวมีขนมตามมา* (หลักเดียวกับการทดลองระฆังของพาฟลอฟ) ถ้าพูดพร้อมโยน คำกับขนมจะปนกัน น้องจะไม่ได้เรียนความหมายของคำ

## 3 คำสำคัญของเกมนี้
- **"cook"** = คำที่มาก่อนขนมจากมือ (ประกาศว่าขนมกำลังมา)
- **"search"** = คำที่มาก่อนขนมที่พื้น (ประกาศว่าขนมจะไปอยู่ที่พื้น)
- **"get it"** = คำอนุญาต "กินเหอะ เก่งมาก" (พูดหลังน้องเลือกนิ่งได้)

*(cook กับ search = คำทำนายรางวัล / get it = คำปลดล็อกให้กิน)*

## เคล็ดลับ & จุดที่มักพลาด
- **กำมือ อย่ายกหนี** (ย้ำอีกครั้ง เพราะพลาดกันบ่อยสุด) — ยกมือ = เกมกลายเป็นการไล่ล่า
- **ให้น้องจ้องขนม ไม่ใช่จ้องเรา** — น้องบางตัวจะหันมามองเราเพื่อ "ขออนุญาต" แต่เราไม่ต้องการแบบนั้น เราต้องการให้น้องตัดสินใจกับ*ตัวขนม*เองว่าจะคว้าหรือไม่คว้า
- **จับจังหวะรางวัลให้ไว** — พอน้องเลือกถูก (นิ่ง) ต้องให้รางวัลเร็ว เพื่อให้น้องมั่นใจว่า "รางวัลนี้ได้มาเพราะฉันเลือกถูก" ถ้าช้าไปน้องจะไม่รู้ว่าได้เพราะอะไร
- **พูดคำก่อนเสมอ** (cook/search มาก่อนขนม)
- **เริ่มจากง่ายก่อน** — ขนมธรรมดาก่อน แล้วค่อยเพิ่มของที่ล่อใจมากขึ้นเมื่อน้องเก่งขึ้น

## เป้าหมายปลายทาง (น้องเก่งระดับไหน?)
เมื่อฝึกจนชำนาญ — อย่างมอมแมม — เราสามารถโยนขนมต่อหน้า หรือส่งขนมเป็นกำมือให้เลย แต่ถ้ายังไม่ได้ยินคำว่า "search" หรือ "get it" น้องจะ **ยืนมองเฉย ไม่กิน** นั่นคือน้องควบคุมตัวเองได้เต็มขั้น เลือกที่จะรอคำอนุญาตเอง

นี่แหละคือคำตอบของเรื่องช็อกโกแลตตอนต้น — วันที่มีของอันตรายตกพื้น น้องที่ผ่านเกมนี้จะยืนมองรอเรา ส่วนน้องทั่วไปจะพุ่งกินก่อนเราจะทันห้าม

