## แก่นของเกมนี้
เราไม่จับขาน้องไปวาง — เราทำให้ perch (ที่ยกสูงเล็กน้อย) เป็นที่ที่น้อง **อยากเอาเท้าหน้าขึ้นไปเอง** แล้วค่อย ๆ ชวนให้ "เดินเท้าหลัง" รอบ ๆ จนน้องค้นพบว่าตัวเองบังคับขาหลังได้ — น้องคิดเอง ขยับเอง เราแค่จัดสถานการณ์

## น้องจะได้อะไร
- รู้ตัวและควบคุมขาหลังได้ (rear-end awareness)
