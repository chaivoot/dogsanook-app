## เตรียมของ
- **perch (จุดหมุน)** = ของยกสูงเล็กน้อยที่ *มั่นคง ไม่ลื่น ไม่โยก* (เช่น ชามคว่ำ กล่องเตี้ย ๆ สมุดหนา ๆ ที่แน่น หรือ balance disc) — ขนาดพอให้เท้าหน้า 2 ข้างขึ้นได้
- **ผ้าสีฟ้า (Safe Spot)** — วางบน perch ช่วงเริ่มต้น น้องรู้จักผ้าดีและมีค่าในใจอยู่แล้ว เลยอยากขึ้นไปยืนเอง (ทางลัดเดียวกับที่ใช้ใน Oxy Spot)
- ขนมชิ้นเล็ก
- ทักษะ Hand Target (เกม 6) ใช้เสริมได้ถ้าน้องยังไม่ขึ้น

⚠️ perch ต้อง **เตี้ยและมั่นคง** ถ้าโยก/ลื่นแล้วน้องตกใจ 1 ครั้ง อาจไม่กล้าขึ้นอีกเลย เริ่มเตี้ยที่สุดก่อน

## วิธีเล่น

### ส่วนที่ 1 — ให้น้องเอาเท้าหน้าขึ้น perch
1. **วางผ้าสีฟ้า (Safe Spot) ไว้บน perch** — น้องเห็นผ้าที่คุ้นเคยและมีค่าในใจอยู่แล้ว เลยอยากเดินไปเหยียบเอง (ถ้ายังไม่ขึ้น ใช้ Hand Target/ขนมนำเสริมได้)
2. จังหวะที่เท้าหน้า (ข้างเดียวหรือสองข้าง) ขึ้นไปบนผ้า/perch → มาร์ก **"yes"** + ให้ขนม
3. **ป้อนขนมเหนือ perch** (ให้น้องกินในตำแหน่งที่เท้ายังอยู่บน perch) → น้องเรียนรู้ว่า "อยู่บนนี้ = ได้กิน"
4. ทำซ้ำจนน้องเดินมาเอาเท้าหน้าขึ้น perch เอง แล้วค่อย ๆ เอาผ้าออกทีหลัง (fade เหมือน Safe Spot)

### ส่วนที่ 2 — สอนให้ "เดินเท้าหลัง" รอบ perch (pivot)
1. พอเท้าหน้าปักบน perch แล้ว → ใช้ขนม/มือนำลำตัวน้องให้โค้งไปด้านข้างช้า ๆ
2. น้องจะต้อง **ก้าวขาหลัง** ตามเพื่อรักษาสมดุล (ขาหน้ายังอยู่บน perch) — นี่คือจังหวะที่ขาหลัง "ตื่น"
3. เริ่มมาร์ก **"yes"** ที่การขยับขาหลังแค่นิดเดียวก่อน แล้วค่อย ๆ สะสมเป็นการเดินรอบทีละนิด
4. ฝึกทั้ง **สองทิศทาง** (ซ้าย–ขวา) เพื่อให้กล้ามเนื้อสมดุล

### ส่วนที่ 3 — เพิ่มความนิ่ง + ความยาก
- ยืดเวลาให้น้องยืนบน perch นิ่ง ๆ นานขึ้น
- เดินรอบได้ครบวงทั้งสองทาง
- ค่อย ๆ ลดการนำด้วยขนม ให้น้องทำจากความเข้าใจ
- ใส่คำสั่ง (เช่นคำเรียกขึ้น perch) **ทีหลัง** — พฤติกรรมมาก่อนคำ

