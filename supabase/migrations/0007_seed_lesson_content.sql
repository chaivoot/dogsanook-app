- **"place"** = คำสั่ง "ไปที่เบาะ" — **ใส่ทีหลังได้ ไม่ต้องรีบ** ให้น้องเข้าใจ *การกระทำ* (ไปอยู่บนเบาะ = ดี) ให้แน่นก่อน แล้วค่อยแปะคำ

## เคล็ดลับ & จุดที่มักพลาด
- **อย่ารีบ** — ทุกขั้นให้น้องมั่นใจก่อนค่อยไปต่อ โดยเฉพาะตอนพับผ้าเล็ก/ย้ายตำแหน่ง
- **ผ้าสีฟ้าเท่านั้น** ไม่ใช่แค่ความสวย แต่เพราะน้องมองเห็นชัด
- **fade ผ้าออกช้า ๆ** — อย่าเพิ่งเอาผ้าออกก่อนน้องจำเบาะได้แน่น
- **อย่ารีบใส่คำ "place"** — พฤติกรรมมาก่อน คำมาทีหลัง
- **เบาะนี้ต้องเป็นที่ดีเสมอ** — อย่าใช้เบาะเป็นที่ลงโทษ/กักบริเวณ ไม่งั้นคุณค่าจะพัง

