- **รางวัลต้องคุ้ม** — พอน้องมาถึง ต้องมีเรื่องดีจริง ๆ (ขนมอร่อย/เล่นสนุก) เพื่อให้ "วิ่งมาหา" เป็นการตัดสินใจที่ดีที่สุดในสายตาน้อง
- **อย่าวิ่งเข้าหาน้อง** — จำหลักเด็กดื้อ: เราวิ่งเข้าหา น้องจะหนี ให้เรา *วิ่งหนี* เสมอเพื่อให้น้องตาม
- **เริ่มระยะใกล้/ที่ปลอดภัยก่อน** — แล้วค่อยเพิ่มระยะและความยากเมื่อน้องเก่งขึ้น
