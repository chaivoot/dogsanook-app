## วิธีเล่น — 3 ระดับ

### ระดับ 1 — หา "หน้า" เจ้าของ (เริ่มจากตรงนี้)
1. เจ้าของ **หมอบลง ขดตัว ก้มหน้าซุกไว้** — ทำตัวเป็นก้อนกลม ๆ ให้น้องมองไม่เห็นหน้า
2. **ส่งเสียงเรียกด้วยเสียงสูง สดใส (เสียงสอง)** ชวนให้น้องอยากเข้ามาหา
3. น้องจะพยายาม *มุด/เขี่ย/หาทางดูหน้า* เรา → พอน้องหาหน้าเราเจอ → **ให้รางวัล + ดีใจด้วยกัน**

ระดับนี้เจ้าของอยู่ตรงหน้าน้องเลย แค่ "ซ่อนหน้า" ด้วยท่าทาง — ปูให้น้องเข้าใจว่า "พยายามหาพ่อแม่จนเจอ = เรื่องดี" แบบง่ายและปลอดภัยที่สุด

### ระดับ 2 — ซ่อนหาในบ้าน
1. พอน้องเก่งระดับ 1 แล้ว → เริ่มไปซ่อนจริง หลังประตู หลังโซฟา หรืออีกห้อง
2. ส่งเสียงเรียก (คำ recall / เสียงสอง) ให้น้องออกตามหา — น้องจะได้ใช้ **จมูกและหู**
3. เจอเมื่อไหร่ = **ฉลองใหญ่** (ขนมพิเศษ/เล่น/เสียงดีใจ)
4. ค่อย ๆ ซ่อนยากขึ้น/ไกลขึ้นในบ้าน

ตอนไปซ่อน ถ้าน้องชอบเดินตาม ใช้ทักษะ "อยู่"/กรงจาก Safe House (เกม 4) ให้น้องรอก่อนได้ — น้องที่ผ่านเกม 4 จะรอได้นิ่ง เล่นคนเดียวง่ายขึ้น

### ระดับ 3 — ซ่อนหานอกบ้าน
1. ขยับออกไปเล่นนอกบ้าน/ในสนาม เมื่อน้องเก่งในบ้านแล้ว
2. ⚠️ **ถ้ายังไม่มั่นใจว่าน้องจะไม่เตลิด — ติดสายจูงยาว 10–15 เมตรไว้ก่อน** น้องยังรู้สึกอิสระเหมือนวิ่งเล่น แต่เรายังคุมได้ถ้ามีเหตุ
3. ซ่อนหลังต้นไม้/หลังรถ ให้น้องตามหาในที่กว้างขึ้น เจอแล้วฉลองเหมือนเดิม

