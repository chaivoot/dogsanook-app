- **น้องเห็นว่า "เล่นกับพ่อแม่ = สนุกที่สุดในโลก"** ไม่ต้องพึ่งขนมตลอด — เจ้าของเองกลายเป็นของเล่นและรางวัลที่ดีที่สุด

เกมนี้เลยเป็นบทปิดที่ทำให้ทุกเกมก่อนหน้า "แน่น" ขึ้น เพราะน้อง *อยาก* อยู่กับเราและฟังเราด้วยใจ ไม่ใช่เพราะขนม

## แก่นของเกมนี้
วนสลับ **ปลุกพลัง (เล่น/วิ่ง) ↔ คุมพลัง (นั่ง)** ไปเรื่อย ๆ — และรางวัลของการควบคุมตัวเองไม่ใช่ขนม แต่คือ **"ได้เล่นต่อ"** (วิ่งไล่กันสนุก)

เราใช้หลัก "เด็กดื้อ" จาก Recall — พอน้องคุมตัวเองได้ เราวิ่งหนีแบบวิ่งเล่น น้องก็ไล่ตามอย่างมีความสุข การเล่นกับเราจึงกลายเป็นรางวัลสูงสุด

## น้องจะได้อะไร
- เล่นสนุกจนมันส์ แล้วเบรกตัวเองนั่งได้ทันทีเมื่อสั่ง (self-control กลางความตื่นเต้น)
- ปล่อย/คืนของเต็มใจ (ปลอดภัย)
- เห็นว่า "เล่นกับพ่อแม่ = สุดยอด" ไม่ต้องพึ่งขนม
- รวมทุกทักษะ (คุมตัวเอง + ปล่อย + วิ่งไล่ + เล่น) มาใช้จริงในเกมเดียว

## เตรียมของ
- ของเล่นสำหรับดึง/ชักเย่อ (เชือก/ตุ๊กตาที่ดึงได้) ที่น้องชอบมาก
- ขนม (ใช้เฉพาะช่วงสอน "ปล่อยของ" ตอนแรกเท่านั้น)
- พื้นที่โล่งพอวิ่งเล่นได้นิดหน่อย ปลอดภัย
- ทักษะจากเกมก่อน: **sit**, release cue (**break**), และหลักเด็กดื้อจาก Recall

## ก่อนเริ่ม — น้องต้องมีทักษะ "ปล่อยของ" ก่อน (จำเป็น!)
ถ้าน้องไม่ยอมปล่อยของ เกมนี้จะสะดุดทันที เพราะฉะนั้นสอนปล่อยของให้ได้ก่อน — มี 2 ขั้น:

1. **ช่วงแรก — แลกของกับขนม:** ระหว่างเล่น ยื่นขนมมาที่จมูกน้อง → น้องปล่อยของเพื่อกินขนม → พอปล่อยก็เก็บของ/มาร์ก ทำซ้ำจนน้องปล่อยง่าย
2. **ขั้นต่อไป — ใช้ "การเล่น" เป็นรางวัลแทนขนม:** พอน้องสนุกกับการเล่นกับเราแล้ว ถ้าน้องไม่ยอมคืนของ → **เรานิ่ง ไม่ขยับเลย** (เกมหยุด) → น้องจะเรียนรู้ว่า "เกมจะสนุกต่อได้ ก็ต่อเมื่อเอาของมาคืน" → **การเอาของมาคืน = สัญญาณเริ่มเกมใหม่** → น้องเลยอยากคืนเอง

*(ใส่คำ เช่น "ปล่อย"/"give" ทีหลังได้ — พฤติกรรมมาก่อนคำ)*

## วิธีเล่น — วงจร เล่น → นั่ง → ไล่

### ส่วนที่ 1 — เล่นดึง/ชักเย่อ (ปลุกพลัง)
เล่นชักเย่อกับน้องให้สนุก ปลุกอารมณ์ขึ้น (arousal up) ให้น้องมันส์กับการเล่น *กับเรา*

### ส่วนที่ 2 — สั่ง "sit" (คุมพลัง)
ระหว่างที่กำลังเล่นสนุกมันส์ ๆ → สั่ง **"sit"** — นี่คือช่วงที่ยากที่สุด เพราะน้องต้อง *เบรกตัวเองกลางความตื่นเต้น* พอน้องควบคุมตัวเองได้ = นั่งลง → มาร์ก **"yes"**

### ส่วนที่ 3 — วิ่งไล่ (ปล่อยพลัง = ฉลอง)
พอน้องนั่งได้ → **ฉลอง!** ให้ release cue (**"break"** หรือคำปล่อยที่ครูใช้) แล้ว **เราวิ่งหนีแบบวิ่งเล่น** → น้องวิ่งไล่ตามอย่างสนุก (หลักเด็กดื้อ: เราหนี น้องไล่) → รางวัลของการคุมตัวเองได้คือ "ได้เล่น/ได้วิ่งไล่" ไม่ใช่ขนม

### ส่วนที่ 4 — วนกลับมาเริ่มใหม่
พอวิ่งไล่กันสนุกแล้ว → กลับมาเล่นชักเย่ออีกรอบ → sit → วิ่งไล่ → วนไปเรื่อย ๆ

วงจร **"เล่น → คุม → ปล่อย"** นี้แหละคือหัวใจของเกม — น้องได้ฝึกขึ้น-ลงอารมณ์ตามเราอยู่ตลอด

## คำที่ใช้ในเกมนี้
- **"sit"** = คำสั่งนั่ง (จุดคุมพลัง)
- **"break"** = release cue ปล่อยให้วิ่งไล่/เล่นต่อ
- **"yes"** = คำมาร์ก
- *(ออปชัน)* **"ปล่อย"/"give"** = คำปล่อยของ ใส่ทีหลัง พฤติกรรมมาก่อนคำ

## เคล็ดลับ & จุดที่มักพลาด
- **ต้องมี "ปล่อยของ" ให้ได้ก่อน** เริ่มวงจรหลัก (จุดพลาดอันดับหนึ่ง) — ไม่งั้นเกมสะดุดตั้งแต่รอบแรก
- **นิ่งจริง ๆ ตอนน้องไม่คืนของ อย่าไล่แย่ง** — เหมือน Smart Choices เป๊ะ (ยกมือหนี/ไล่แย่ง = กลายเป็นเกมไล่ล่า) การนิ่ง = เกมหยุด แล้วน้องจะเลือกคืนเอง
- **รางวัลคือการเล่น ไม่ใช่ขนม** — นี่คือจุดที่ทำให้เจ้าของกลายเป็นของเล่นที่ดีที่สุด อย่าเผลอกลับไปใช้ขนมเป็นรางวัลหลัก
- **วิ่งหนี อย่าวิ่งเข้าหา** (หลักเด็กดื้อ) เพื่อให้น้องไล่
- **สั่ง sit ตอนกำลังสนุกมันส์คือความยากจริง** — เริ่มจากจังหวะที่ตื่นเต้นไม่มากก่อน แล้วค่อยเพิ่มระดับความมันส์ทีละนิด
- **จบเกมตอนน้องยังสนุกอยู่** อย่าเล่นจนน้องเบื่อ/หมดแรง เพื่อให้น้องอยากเล่นอีกในครั้งหน้า

## เป้าหมายปลายทาง (น้องเก่งระดับไหน?)
เมื่อฝึกจนชำนาญ — อย่างมอมแมม — น้องจะเล่นสนุกจนตื่นเต้นสุด ๆ แล้วพอสั่ง "sit" ก็ **เบรกตัวเองนั่งได้ทันที** คืนของเต็มใจ แล้วพร้อมวิ่งไล่เล่นต่อเมื่อได้ "break" = น้องขึ้น-ลงอารมณ์ตามเราได้อย่างสมบูรณ์ และเห็นว่าเราคือเพื่อนเล่นที่ดีที่สุด — เป็นบทปิดที่มัดรวมทุกทักษะของทั้งคอร์สไว้ด้วยกัน

