เคยไหม... เวลาจะจับปลอกคอน้อง จะพาเข้าบ้าน หรือต้องจับตัวตอนมีเหตุฉุกเฉิน แล้วน้องหลบ วิ่งหนี หรือตัวเกร็ง?

เกมนี้เปลี่ยนความรู้สึกของน้องให้ **"การถูกจับตัว = เรื่องดีกำลังจะเกิด"** จนน้องยื่นคอเข้ามาให้เราจับเอง และในวันที่น้องตกใจหรือตื่นเต้น แค่เราแตะตัว น้องก็รู้สึกปลอดภัยและกลับมาสงบได้

พร้อมกันนั้น เกมนี้ยังสอน **"คำ" พื้นฐาน 2 คำ** ที่เราจะใช้ในทุกเกมต่อจากนี้ เหมือนสอนให้น้องรู้จักตัวอักษรก่อนหัดอ่านหนังสือ

## น้องจะได้อะไรจากเกมนี้
- ยอมให้จับตัว/จับปลอกคอโดยไม่หนี (สำคัญมากเวลาฉุกเฉิน)
- รู้สึกปลอดภัยเมื่อถูกสัมผัส
- เข้าใจคำว่า **"คุ้ก"** = จะได้กินขนมจากมือ
- เข้าใจคำว่า **"search"** = ขนมอยู่ที่พื้น ให้ไปหากิน

## เตรียมของ
- ปลอกคอ (เกมนี้จำเป็นต้องมี)
- ขนมชิ้นเล็กที่น้องชอบ แบ่งเป็นชิ้นพอดีคำ
- พื้นที่สงบ ไม่มีอะไรรบกวนมาก (เริ่มในบ้านก่อน)

## วิธีเล่น

### ส่วนที่ 1 — สอนคำว่า "คุ้ก" (ขนมจากมือ)
1. ใช้มือแตะตัวหรือจับปลอกคอน้องเบา ๆ
2. พูดคำว่า **"คุ้ก"** แล้วป้อนขนมจากมือทันที
3. ทำซ้ำหลาย ๆ ครั้ง สลับหลายจังหวะในวัน

พอทำไปเรื่อย ๆ น้องจะเริ่ม **ยื่นคอเข้ามาหามือเราเอง** เพราะเรียนรู้แล้วว่า "จับปลอกคอ = ได้กิน" — นี่คือสัญญาณว่าเกมกำลังได้ผล

### ส่วนที่ 2 — สอนคำว่า "search" (ขนมที่พื้น)
1. พูดคำว่า **"search"** แล้วโยนขนมลงที่พื้น
2. ปล่อยให้น้องก้มไปหากิน
3. ทำซ้ำจนน้องได้ยินคำนี้แล้วรู้ว่า "มีขนมที่พื้น"

### ส่วนที่ 3 — ฝึกสองคำคู่กัน
สลับใช้ **"คุ้ก"** (กินจากมือ) กับ **"search"** (กินจากพื้น) ในช่วงเล่นเดียวกัน ให้น้องเริ่มแยกออกว่าได้ยินคำไหน = กินจากตรงไหน

*(ช่วงนี้ยังไม่ใช่ "เกม" เต็มรูปแบบ — เราแค่ทำให้น้องคุ้นกับคำก่อน เพื่อเอาไปใช้ในเกมถัด ๆ ไป)*

### ส่วนที่ 4 — ขยายตำแหน่งที่จับ
พอน้องโอเคกับการจับปลอกคอแล้ว ค่อย ๆ ขยับไปจับตำแหน่งอื่น: จับตัว จับหลัง จนน้องยอมให้สัมผัสได้ทั้งตัว โดยยังพูด **"คุ้ก"** และป้อนขนมเหมือนเดิม

