## วิธีเล่น

### เตรียมมือก่อน (ครูต้องซ้อมเองก่อนสอนหมา)
- มือหนึ่ง = **ถือขนม** (มือจ่ายรางวัล) / อีกมือ = **target** (มือที่ให้น้องแตะ)
- พอน้องแตะ target → ปล่อยขนมจากมือจ่าย **มาที่มือ target** เพื่อสร้างค่าให้มือ target (น้องจะเรียนรู้ว่า "แตะมือแล้วขนมโผล่มาที่มือ" ไม่ใช่ตามขนม)
- **เคล็ดลับ:** ปล่อยขนมจากมือจ่ายให้สูงหน่อย อย่าให้น้องเห็น/ได้กลิ่นมือจ่ายก่อน ไม่งั้นน้องจะไปโฟกัสมือขนมแทนที่จะเรียนรู้ว่า "แตะ target แล้วขนมถึงจะมา" (ซ้อมมือให้คล่องก่อน)

### จังหวะแรก — ให้น้องแตะเอง
1. **ยกมือ target ขึ้นทันที** → น้องจะสงสัยว่า "มีอะไรที่มือ?" แล้วเข้ามาดม/สำรวจเอง (ถ้ามีกลิ่นขนมติดมือ target จะยิ่งเร่งให้เร็วขึ้น)
2. พอจมูกแตะมือ → **ชิงจังหวะมาร์ก "yes" ให้ไว** แล้วปล่อยขนมมาที่มือ target
3. ทำซ้ำ จนน้องเข้าใจว่า "แตะมือ = เรื่องดี"

⚠️ **กฎเหล็ก: มือต้องอยู่นิ่ง ให้น้องมาแตะเอง — ห้ามเอามือไปแตะจมูกน้อง** ถ้าเราขยับมือไปหาน้อง น้องจะกลายเป็นฝ่ายรับ (ไม่ได้เลือกทำเอง) และจะไม่เรียนรู้ที่จะเป็นคนเริ่ม เราต้องการให้ "มือมีค่าจนน้องอยากมาแตะเอง"

### ไม่ใช้คำสั่ง (no cue)
เกมนี้ **ไม่ต้องมีคำสั่ง** — "การยกมือขึ้น" คือสัญญาณในตัวเองอยู่แล้ว

เหตุผล: เราอยากให้น้องจดจ่อที่มือเราตลอด ในเลเวลสูงเราเล่นสนุกได้ เช่นรีบยกมือขึ้นแวบเดียว ถ้าน้องแตะไม่ทัน มือก็หายไป → น้องต้องมีสมาธิ ถ้าใส่คำสั่ง น้องจะเรียนรู้ว่า "ไปสนใจอย่างอื่นก่อนได้ รอฟังเสียงค่อยกลับมา" = เสียสมาธิ

### พัฒนาต่อ — จากแตะแวบเดียว
- เริ่มจากน้องแตะถี่ ๆ
- **ระวังเรื่องฟัน:** บางตัวไม่แน่ใจว่าต้องใช้ฟันไหม (มอมแมมเคยเป็น) — ให้รางวัล **เฉพาะตอนน้องใช้จมูกแตะนุ่ม ๆ** เท่านั้น ถ้าน้องใช้ฟัน/งับ ไม่ต้องมาร์ก ไม่ต้องให้รางวัล (มือนิ่งไว้เฉย ๆ) น้องจะค่อย ๆ เข้าใจเองว่า "จมูกแตะ = ได้ / ฟัน = ไม่ได้"
- **แตะค้าง:** น้องเรียนรู้เองผ่านจังหวะให้รางวัล — พอน้องเลือกมาแตะแล้ว (จมูกอยู่ที่มือ) เราค่อย **ดันมือเข้าหาได้** (เพราะตอนนี้น้องแตะมือเราแล้ว ไม่ใช่เราไปแตะน้อง) → ยืดเวลาก่อนให้รางวัล → น้องเรียนรู้ว่า "ค้างไว้นานขึ้น = ได้รางวัล"
- **ขยายความยาก:** ยื่นมือไกลขึ้น / สลับซ้าย-ขวา / เปลี่ยนตำแหน่งสูง-ต่ำ

