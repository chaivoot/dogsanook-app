## เคล็ดลับ & จุดที่มักพลาด
- **อย่ารีบ** — ให้น้องได้กินทุกครั้งที่ถูกจับในช่วงแรก เพื่อสร้างความรู้สึกดีให้แน่นก่อน
- จับเบา ๆ ก่อน ถ้าน้องยังไม่ชิน อย่าเพิ่งจับแน่นหรือรั้ง
- ทำบ่อย ๆ สั้น ๆ ดีกว่าทำนาน ๆ ครั้งเดียว — วันละหลายรอบ รอบละไม่กี่นาที
- ถ้าน้องหลบ แสดงว่าเราเร็วไป ถอยกลับไปขั้นที่ง่ายกว่า

