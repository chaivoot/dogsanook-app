พูดง่าย ๆ คือ เราสอนให้น้อง **พกความปลอดภัยติดตัวไปไหนก็ได้**

## แก่นของเกมนี้
เราไม่ได้บังคับให้น้อง "อยู่นิ่ง ๆ" บนเบาะ — เราทำให้เบาะกลายเป็น *ที่ที่ดีที่สุดในโลกของน้อง* จนน้อง **อยากขึ้นไปอยู่เอง** และรู้สึกผ่อนคลายเมื่ออยู่บนนั้น

## น้องจะได้อะไร
- มีที่ปลอดภัยของตัวเองที่พกไปไหนก็ได้
- สงบลงได้เองแม้อยู่นอกบ้าน หรือในที่แปลกใหม่
- มีที่ให้ "ไปอยู่" เวลาเราต้องการ (เช่นตอนมีแขก ตอนกินข้าว)

