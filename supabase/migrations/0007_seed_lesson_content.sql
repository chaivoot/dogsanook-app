## แก่นของเกมนี้ — "จุดข้างขา = ที่ที่ดีที่สุด" (เป็น Safe Spot ที่เคลื่อนที่ได้)
จำ Safe Spot ได้ไหม — เราทำให้เบาะมีค่าจนน้องอยากขึ้นไปอยู่เอง Oxy Spot ใช้หลักเดียวกันเป๊ะ แต่ "จุด" นี้ไม่ได้อยู่กับที่ มันคือ **ข้างขาเรา** ที่เคลื่อนที่ไปพร้อมเรา

เราไม่ดึงสาย ไม่สั่ง — เราแค่ทำให้ทุกเรื่องดี (ขนม + มาร์ก yes) เกิดขึ้น *ตรงจุดข้างขา* เท่านั้น จนน้องค้นพบเองว่า "อยู่ตรงนี้แหละคุ้มที่สุด" แล้วเลือกมาเกาะข้างเราเอง

## ทำไมชื่อ "Oxy Spot" — จุดนี้ให้มากกว่าขนม
ชื่อ Oxy Spot มาจาก **oxytocin (ฮอร์โมนแห่งความผูกพัน)** เพราะจุดข้างขาเราไม่ได้มีค่าแค่ "มีขนม" เท่านั้น

การที่น้องได้อยู่ **ใกล้ชิดพ่อแม่ + ได้รับแต่เรื่องดี ๆ ตรงจุดนั้นซ้ำ ๆ** ช่วยกระตุ้นการหลั่งออกซิโทซินทั้งในน้องและในตัวเรา — น้องเลยไม่ได้แค่ "ทนอยู่ข้างเราเพื่อรอขนม" แต่ **รู้สึกดี อุ่นใจ และผูกพัน** เมื่ออยู่ตรงนี้

นี่คือเหตุผลที่ความอยากอยู่ข้างเรามัน "ติด" แม้วันที่ไม่มีขนม — เพราะตัวตำแหน่งเองกลายเป็นที่ที่น้องรู้สึกใกล้ชิดและปลอดภัยที่สุด และเป็นเหตุผลว่าทำไม Oxy Spot ถึงเป็นฐานที่ดีของการเดินด้วยกัน: น้องเดินข้างเราเพราะ *อยาก* อยู่ใกล้ ไม่ใช่เพราะถูกสายจูงรั้ง

## น้องจะได้อะไร
- เดินชิดข้างเราได้สบาย ๆ ไม่ลากสาย ไม่พุ่งไปข้างหน้า
- กลับมาหาจุดข้างขาเอง แม้เจอสิ่งเร้า (หมาตัวอื่น คนเดินผ่าน)
- โฟกัสที่เรามากขึ้นเวลาอยู่ข้างนอก
- เป็นฐานของการเดินสายจูงหย่อน + ท่า heel + เกมขั้นสูงต่อ ๆ ไป

## เตรียมของ
- ขนมชิ้นเล็กที่น้องชอบ (เกมนี้ใช้เยอะหน่อย เพราะเราจ่ายถี่)
- พื้นที่สงบ เริ่มในบ้าน — **ยังไม่ต้องใส่สายจูงก็ได้** (สร้าง "ใจอยากอยู่" ก่อน แล้วค่อยใส่สาย)
- เลือก **ข้างที่ถนัด** — ปกตินิยมข้างซ้าย แต่เลือกข้างไหนก็ได้ ขอให้ *คงที่ข้างเดิม* ตลอด (อย่าสลับไปมาช่วงแรก)
- **แพลงค์ไม้ยาวแนวนอน** (ตัวช่วยสำหรับน้องที่ยังงงหรือนั่งไม่ตรง — ดูวิธีใช้ด้านล่าง)
- **ผ้าสีฟ้า** จาก Safe Spot (ปูบนแพลงค์ในช่วงเริ่มต้น)

## วิธีเล่น

### ส่วนที่ 1 — สอนว่า "จุดข้างขา = ได้ขนม"
1. ให้น้องมายืนข้างขาเรา (ข้างที่เลือก) หันหน้าไปทางเดียวกับเรา
2. **ทริคจ่ายขนม — แตะตัวเองก่อนป้อน:** ก่อนป้อนขนม ให้เอามือ **แตะตัวเราเองตรงจุดที่จะจ่าย** ก่อน (ข้อพับเข่า / ต้นขา / สะโพก) เพื่อ "มาร์กจุด" ให้น้องรู้ว่าต้องเอาหัวมาปักตรงไหน แล้วค่อยป้อนขนมตรงจุดนั้น
   - **เลือกระดับตามความสูงของน้อง:** น้องตัวเล็กใช้จุดต่ำ (ข้อพับเข่า) · น้องตัวสูงใช้ต้นขา–สะโพก
3. มาร์ก **"yes"** แล้วป้อนขนมตรงจุดเดิมชิดขา ทำซ้ำ ๆ ให้น้องรู้สึกว่า "ยืนตรงนี้ = ขนมโผล่มาเรื่อย ๆ"

**ทำไมต้องจ่ายตรงจุดชิดขา:** ตำแหน่งที่เราจ่ายขนม = ตำแหน่งที่น้องจะปักหลัก ถ้าจ่ายสูงหรือยื่นออกไปข้างหน้า น้องจะขยับตามมือไปผิดที่ เราอยากให้หัวน้อง "ล็อก" อยู่ข้างขาพอดี

### ตัวช่วยพิเศษ: แพลงค์ไม้ + ผ้าสีฟ้า (สำหรับน้องที่ยังงง / นั่งไม่ตรง)
น้องบางตัวยังงงว่าต้องยืนตรงไหน หรือนั่งเบี้ยว/หันเฉียง — ใช้ **แพลงค์ไม้ยาววางแนวนอนข้างตัวเรา** เป็น "ขอบนำทาง" ช่วยได้ 2 อย่าง:

1. **จัดให้หันหน้าถูกทาง** — แพลงค์เป็นแนวยาว น้องเลยเข้าท่าขนานกับตัวเราเองโดยธรรมชาติ
2. **จัดท่านั่งให้สวย** — สำหรับน้องที่นั่งเบี้ยว แพลงค์ช่วยให้ตัวตรงขึ้นเอง

**ช่วงเริ่มต้นให้ปูผ้าสีฟ้าบนแพลงค์** — น้องรู้จักผ้าสีฟ้าดีอยู่แล้วจาก Safe Spot (เห็นชัด + มีค่าในใจ) เลยอยากขึ้นไปยืน/นั่งบนนั้นเอง ทำให้เข้าจุดง่ายขึ้นมาก

แพลงค์ไม่ใช่การกด/รั้งน้อง — มันแค่ทำให้ "ท่าตรง" เป็นทางที่ง่ายที่สุด น้องเลยเลือกเข้าท่าถูกเอง พอน้องชินแล้วค่อย ๆ เอาแพลงค์และผ้าออก (fade เหมือนที่ทำกับผ้าใน Safe Spot)

### ส่วนที่ 2 — ให้น้อง "หาจุด" เจอเอง (ใช้ search)
1. พูด **"search"** แล้วโยนขนมออกไป → น้องวิ่งไปกิน
2. พอน้องกินเสร็จ **เดินกลับมาเข้าจุดข้างขาเอง** → มาร์ก **"yes"** + ป้อนขนมตรงจุด
3. ทำซ้ำ (search โยนออก → น้องกลับมาเข้าจุด → yes + ขนม) จนน้อง "รีเซ็ต" แล้ววิ่งกลับมาเสียบข้างขาเราเองทุกครั้ง

*(กลไกนี้เหมือน Safe Spot เป๊ะ — แค่ "จุด" ย้ายจากเบาะมาเป็นข้างขาเรา)*

### ส่วนที่ 3 — เพิ่มการเคลื่อนที่ (จุดข้างขาเดินไปพร้อมเรา)
1. พอน้องเสียบข้างขาแล้ว → **ก้าวไป 1 ก้าว** ถ้าน้องขยับตามมาอยู่ข้างขาต่อ → yes + ขนมตรงจุด
2. ค่อย ๆ เพิ่มเป็น 2-3 ก้าว แล้วค่อยยาวขึ้น
3. น้องเรียนรู้ว่า "จุดข้างขา" เคลื่อนที่ได้ และการเกาะจุดไว้ระหว่างเดิน = ได้รางวัลเรื่อย ๆ

เริ่ม **จ่ายถี่ (ทุกก้าว)** ก่อน แล้วค่อย ๆ ห่างขึ้น (2 ก้าวจ่ายที → 3 ก้าวจ่ายที) เมื่อน้องมั่นแล้ว

### ส่วนที่ 4 — คำปล่อย "break" (สอนให้ "อยู่จุด" จนกว่าจะปล่อย)
1. พอน้องมายืน/นั่งในจุดข้างขาแล้ว → การออกจากจุดต้องมาจากคำ **"break"** เท่านั้น (= "พักได้ ออกได้" คำเดียวกับ Safe House)
2. ค่อย ๆ ให้น้องอยู่จุดนานขึ้นก่อนพูด break → น้องเรียนรู้ว่า "อยู่จุดต่อ = ได้รางวัล"

**ถ้าน้องเดินออกเองก่อนได้ยิน "break":** จับปลอกคอ (ใช้ทักษะจาก **Human Touch**) พากลับมานั่งข้างขาเหมือนเดิมอย่างใจเย็น — ไม่ดุ ไม่ว่า น้องจะเรียนรู้ว่า "ออกจากจุดได้เมื่อได้ยิน break เท่านั้น" (ไม่ใช่การลงโทษ แค่จัดการผลของการเลือก แบบเดียวกับ Smart Choices)

### ส่วนที่ 5 — ใส่สายจูง + ใส่คำ heel (ทีหลัง ไม่รีบ)
- พอน้องอยากอยู่ข้างขาเองแล้ว **ค่อยใส่สายจูง** — สายควรหย่อนตลอด เพราะน้องอยู่ข้างเราด้วยใจ ไม่ใช่เพราะถูกรั้ง
- ถ้าน้องหลุดไปข้างหน้า → **ไม่กระชาก** แค่ใช้ "search" หรือชวนให้กลับมาเข้าจุด แล้วรีวอร์ดเมื่อกลับมา
- **ใส่คำสั่ง heel ทีหลังได้** — ให้น้องเข้าใจ *การกระทำ* (อยู่จุดข้างขา = ดี) ให้แน่นก่อน แล้วค่อยแปะคำ (หลักเดียวกับ place / เข้ากรง)

## คำที่ใช้ในเกมนี้
- **"yes"** = คำมาร์ก "ทำถูกแล้ว!" (มาร์กจังหวะน้องเข้าจุด/อยู่จุด)
- **"search"** = โยนขนมออก ให้น้องไปหา แล้วรีเซ็ตกลับมาเข้าจุด — ปูไว้ตั้งแต่เกม 1
- **"break"** = คำปล่อย "พักได้ ออกได้" — คำเดียวกับ Safe House
- *(ออปชัน)* คำสั่ง **heel** / คำเรียกเข้าจุด — ใส่ทีหลัง พฤติกรรมมาก่อนคำ

## เคล็ดลับ & จุดที่มักพลาด
- **แตะตัวเองมาร์กจุดก่อนป้อน** แล้วจ่ายขนมตรงจุดชิดขาเสมอ (พลาดกันบ่อยสุด) — จ่ายผิดที่ = น้องปักหลักผิดที่
- **ใช้แพลงค์ + ผ้าสีฟ้าช่วยน้องที่ยังงง/นั่งไม่ตรง** แล้ว fade ออกช้า ๆ เมื่อน้องเข้าท่าเองได้ อย่าเอาออกเร็วเกิน
- **อย่ารีบใส่สายจูง/อย่ากระชาก** — เราสร้าง "ใจอยากอยู่" ก่อน สายจูงมาทีหลัง และมีไว้กันหลุดเฉย ๆ ไม่ใช่ไว้รั้ง
- **เลือกข้างเดียวคงที่** ช่วงแรกอย่าสลับ น้องจะงง
- **เริ่มในที่สงบก่อน** แล้วค่อยเพิ่มสิ่งเร้าทีละนิด (ในบ้าน → หน้าบ้าน → ที่มีคน/มีหมา) เมื่อน้องมั่นขึ้น
- **จ่ายถี่ตอนแรก** แล้วค่อยห่าง — ถ้าห่างเร็วไปน้องจะหลุดจุด ถอยกลับไปจ่ายถี่ก่อน
- **การออกจากจุดต้องมาจาก "break" เท่านั้น** ออกเองก่อน = จับปลอกคอพากลับมาใจเย็น ๆ ไม่ดุ
- **อย่าใส่คำ heel เร็วไป** — พฤติกรรมมาก่อน คำมาทีหลังเสมอ

## เป้าหมายปลายทาง (น้องเก่งระดับไหน?)
เมื่อฝึกจนชำนาญ — อย่างมอมแมม — น้องจะ **เสียบเข้าจุดข้างขาเราเอง** ท่าตรง หันหน้าถูกทาง (ไม่ต้องใช้แพลงค์แล้ว) และเดินเกาะข้างไปด้วยกันได้ สายจูงหย่อนตลอด แม้เดินผ่านสิ่งเร้า น้องก็เลือกกลับมาอยู่ข้างเรา และรอ "break" ก่อนออก เพราะข้างเรา = ที่ที่ดีที่สุด

## น้องพร้อมไปเกมถัดไปเมื่อ...
- น้องเดินกลับมาเข้าจุดข้างขาเอง ท่าตรง (ทั้งตอนอยู่กับที่และตอนเดิน)
- น้องอยู่ข้างขาได้ระหว่างเดินหลายก้าว สายจูงหย่อน
- น้องรอ "break" ก่อนออกจากจุด และกลับมาเข้าจุดได้แม้มีสิ่งเร้าเบา ๆ

