## วิธีเล่น

### ส่วนที่ 1 — ทำให้น้องเข้ากรงเอง
เลือกวิธีเริ่มได้ 2 แบบ:

- **ทางลัด (ถ้าผ่าน Safe Spot แล้ว):** เอาผ้าสีฟ้าที่มีค่าแล้วไปวางในกรง → น้องอยากเข้าเพราะรู้จักผ้าดี
- **เริ่มจากศูนย์:** โยนขนมเข้าไปในกรง → น้องเข้าไปกิน → ออกมา → โยนขนมเข้าใหม่ → ทำซ้ำไปเรื่อย ๆ

ทำซ้ำจนน้อง **เริ่มเดินเข้ากรงเอง**

### ส่วนที่ 2 — สอนว่า "ข้างในสุด = ดีที่สุด"
1. พอน้องเข้ากรงเอง → มาร์กด้วยคำ **"yes"** ตั้งแต่จังหวะที่น้องเข้า (บอกทันทีว่าการเข้ากรงนี่แหละถูกแล้ว)
2. ให้ขนมจากมือ โดย **ยื่นมือเข้าไปลึก ๆ ถึงด้านในสุดของกรง** → น้องจะเรียนรู้ว่า "รางวัลอยู่ด้านในสุด" จึงเข้าไปอยู่ลึก ไม่ใช่แค่โผล่หัวเข้าไปครึ่งตัว

### ส่วนที่ 3 — สอนให้ "อยู่" ต่อ (สร้างระยะห่าง)
1. เมื่อน้องอยู่ในกรง ลองถอยห่างออกมานิดหน่อย
2. ถ้าน้อง **ยังอยู่ในกรง** → รีบเดินกลับไปให้ขนม
3. ค่อย ๆ **เพิ่มระยะห่าง** ให้มากขึ้นทีละนิด → น้องเรียนรู้ว่า "อยู่ในกรงต่อ = ได้รางวัล" แม้เราจะห่างออกไป

### ส่วนที่ 4 — คำปล่อย "break" + ชวนเล่น
- ใช้คำ **"break"** = "พักได้ อยากทำอะไรก็ทำ" เป็นสัญญาณว่าน้องออกจากกรงได้
- **เคล็ดลับ:** พอพูด "break" แล้วน้องออกมา ให้ **ชวนน้องเล่นเลย** → กรงจะยิ่งเป็นที่ที่ดี เพราะ "เข้ากรงไปแล้ว นอกจากได้ขนม ยังเป็นสัญญาณว่าเดี๋ยวได้เล่นกับพ่อแม่ด้วย"

### ถ้าน้องออกก่อนได้ยิน "break"
จับปลอกคอ (ใช้ทักษะจากเกม **Human Touch**) พาน้องกลับเข้ากรงใหม่อย่างใจเย็น — ไม่ดุ ไม่ว่า น้องจะเรียนรู้ว่า "การออกเกิดขึ้นได้เมื่อได้ยิน break เท่านั้น" (เราไม่ได้ลงโทษ แค่จัดการผลของการเลือก แบบเดียวกับ Smart Choices)

