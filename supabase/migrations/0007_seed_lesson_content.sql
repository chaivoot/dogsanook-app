3. **ถึงตัว = รางวัลใหญ่** — พอน้องมาถึง ให้รางวัล (ขนม/ของเล่น) แล้วฉลองให้สนุก เพื่อให้น้องเรียนรู้ว่า "วิ่งมาหา = เรื่องดีที่สุด"

### เพิ่มความอยากอีกเท่าตัว (ถ้ามีผู้ช่วย)
ให้ผู้ช่วยรั้งน้องไว้เบา ๆ พอเป็นพิธี (เหมือนน้องโดนห้ามไม่ให้ตาม) — พอเราพูดคำเรียกแล้ววิ่งหนี ผู้ช่วยค่อยปล่อย → ความอยากวิ่งตามจะพุ่งขึ้น *เท่าตัว* เพราะ "ยิ่งห้ามยิ่งอยาก" นี่คือเคล็ดลับสำคัญข้อหนึ่งของเกมนี้

### ถ้าฝึกคนเดียว (ไม่มีผู้ช่วย)
ฝึกคนเดียวก็ทำได้ครับ มีเทคนิคเฉพาะที่ครูจะสอนให้ในคลาส — และถ้าน้องผ่านเกม **Safe House** มาแล้ว จะยิ่งง่ายขึ้น ปรึกษาครูได้เลยตอนเรียน

## เลือกคำเรียก recall (สำคัญมากสำหรับบ้านคนไทย)
**อย่าใช้ชื่อน้องเป็นคำเรียก recall**

เพราะคนไทยเรียกชื่อหมาในทุกอารมณ์ — เรียกเล่น เรียกกินข้าว และโดยเฉพาะ **เรียกดุ/เรียกห้าม** (เวลาน้องกำลังจะทำอะไรที่เราไม่อยากให้ทำ เราจะเผลอเรียกชื่อดัง ๆ) ชื่อน้องเลย "ปนเปื้อน" หลายอารมณ์

พอเอาชื่อมาใช้เรียกให้กลับมา น้องจะงงว่า *"เรียกให้มา หรือกำลังจะโดนดุ?"* → ลังเล ไม่กล้ามา

**วิธีแก้:** เลือก *คำใหม่* เป็นสัญญาณ recall โดยเฉพาะ — คำที่

1. ไม่ใช่ชื่อน้อง
2. ไม่เคยใช้ดุ/ห้าม
3. ฟังสดใส พูดแล้วรู้สึกดี

แล้วใช้คำนี้ **เฉพาะตอนเรียกกลับมาเท่านั้น** เพื่อให้มัน "สะอาด" แปลว่า "มาหาเราสิ มีเรื่องดี" อย่างเดียว

### เกร็ดจากครู 🐾
