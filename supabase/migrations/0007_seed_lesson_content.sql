- ขนม 2 ระดับ: ขนมธรรมดา/อาหารเม็ด + ขนมพิเศษที่อร่อยกว่า
- เบาะจริงของน้อง (ตัวที่อยากให้น้องใช้/พกไปด้วย)

🔵 **ทำไมต้องผ้าสีฟ้า?** หมามองเห็นสีฟ้าและเหลืองได้ชัดที่สุด (ต่างจากคน) และพื้นบ้านส่วนใหญ่มักมีโทนเหลือง/น้ำตาลปนอยู่ — ผ้าสีฟ้าจึงตัดกับพื้นและทำให้น้อง *มองเห็นผ้าได้ง่าย* รู้ว่าต้องเหยียบตรงไหน

## วิธีเล่น

### ส่วนที่ 1 — ทำให้ผ้ามีค่า
1. ปูผ้าสีฟ้าตรงหน้าเรา โยนขนมลงบนผ้าก่อนสัก 2-3 ครั้ง ให้น้องคุ้นกับการอยู่บนผ้า
2. โยนขนมออก *นอกผ้า* พร้อมพูด **"search"** (น้องวิ่งไปกิน)
3. พอน้องกินเสร็จแล้ว **กลับมาเหยียบผ้า** (ส่วนใดของตัวก็ได้) → มาร์กด้วยคำ **"yes"** แล้วให้ขนมจากมือ
4. ทำซ้ำ (search ออก → กลับมาเหยียบผ้า → yes + ขนม) จนน้องเข้าใจว่า **"เหยียบผ้า = ได้กิน"** แล้วเริ่มขยับมายืนบนผ้าเต็มตัวเอง

### ส่วนที่ 2 — เพิ่มความยาก (ค่อย ๆ อย่ารีบ)
- **พับผ้าให้เล็กลง** ทีละนิด
- **ย้ายตำแหน่งผ้า** จากตรงหน้าเรา → ไปด้านข้าง

ขั้นนี้คือ challenge — ทำช้า ๆ ถ้าน้องเริ่มงง ให้ถอยกลับไปขั้นที่ง่ายกว่า

### ส่วนที่ 3 — โอนคุณค่าจากผ้า → เบาะจริง (สำคัญมาก)
เป้าหมายจริงไม่ใช่ให้น้องรักผ้าสีฟ้า แต่รัก **เบาะของตัวเอง** ที่พกไปได้ วิธีคือ:

1. เอาผ้าสีฟ้าไปกางไว้ **บนเบาะจริง** แล้วฝึกซ้ำบนนั้น
2. ทำซ้ำจนน้องเชื่อมโยงว่า "เบาะนี้ = ที่ดี" (ไม่ใช่แค่ผ้า)
3. หลัง ๆ ค่อย ๆ **เอาผ้าออกระหว่างฝึก** → น้องจะยังจำเบาะได้ แม้ไม่มีผ้าแล้ว

ผ้าสีฟ้าเป็นแค่ "เครื่องมือชั่วคราว" ที่ค่อย ๆ จางหายไป เหลือแค่เบาะจริงที่น้องรัก

### ส่วนที่ 4 — ระบบรางวัล 2 ระดับ (ทำให้เบาะคือที่ที่ดีที่สุด)
- ใช้ **"search"** เรียกน้องออกจากเบาะ → ได้ขนมธรรมดา/อาหารเม็ด
- พอน้อง **กลับมาที่เบาะ** → ได้ขนมพิเศษที่อร่อยกว่า

น้องจะเรียนรู้ว่า "ข้างนอกก็ดี... แต่กลับมาบนเบาะดีที่สุด" → อยากกลับมาอยู่บนเบาะเอง

## คำที่ใช้ในเกมนี้
